import fs from 'node:fs';
import path from 'node:path';

const scriptDir = path.dirname(new URL(import.meta.url).pathname);
const contractsDir = path.resolve(scriptDir, '..');
const specPath = path.join(contractsDir, 'specs', 'phase03-view-bindings.json');
const frontendDir = path.resolve(contractsDir, '..', 'frontend');
const outputPath = path.join(frontendDir, 'services', 'generated', 'phase03-bindings.ts');

const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));

const renderType = (type) => {
  const lines = [
    `export interface ${type.name} {`,
    ...type.fields.map((field) => `    ${field}`),
    '}',
  ];
  return lines.join('\n');
};

const renderCommand = (command) => {
  const body = command.retry
    ? `withRetry(() => invoke('${command.name}', ${command.requestExpression}))`
    : `invoke('${command.name}', ${command.requestExpression})`;
  return `    ${command.name}: ${command.signature} => ${body},`;
};

const output = `// Auto-generated from contracts/specs/phase03-view-bindings.json by contracts/scripts/generate-phase03-bindings.mjs.
// Do not edit this file directly.

import type { Page } from '../normalization';

${spec.types.map(renderType).join('\n\n')}

export interface Phase03BindingDeps {
    invoke<T>(cmd: string, args?: unknown): Promise<T>;
    withRetry<T>(fn: () => Promise<T>): Promise<T>;
}

export const createPhase03Bindings = ({ invoke, withRetry }: Phase03BindingDeps) => ({
${spec.commands.map(renderCommand).join('\n')}
});
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);
console.log(`Wrote ${path.relative(process.cwd(), outputPath)}`);
